#!/usr/bin/env python3
"""Generate known-answer vectors for src-tauri/src/crypto from INDEPENDENT implementations.

Uses Python's `cryptography` (OpenSSL) for Argon2id / HKDF-SHA512 / ChaCha20-Poly1305, the
stdlib for NFKC, and a small pure-Python HChaCha20 to build XChaCha20-Poly1305. The HChaCha20
and XChaCha20 constructions are first checked against the IETF draft-irtf-cfrg-xchacha vectors,
so a mistake here cannot silently produce wrong expectations.

    python3 scripts/gen_crypto_kat.py            # writes src-tauri/src/crypto/kat_vectors.rs
    python3 scripts/gen_crypto_kat.py --check    # exit 1 if the committed file is out of date

Re-run only when the specification in ai-docs/CRYPTO_SPEC.md changes.
"""
import json
import pathlib
import struct
import sys
import unicodedata

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.argon2 import Argon2id
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

OUT = pathlib.Path(__file__).resolve().parent.parent / "src-tauri" / "src" / "crypto" / "kat_vectors.rs"


# ---------------------------------------------------------------- HChaCha20 / XChaCha20-Poly1305
def _rotl(x, n):
    return ((x << n) & 0xFFFFFFFF) | (x >> (32 - n))


def _quarter(s, a, b, c, d):
    s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = _rotl(s[d] ^ s[a], 16)
    s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = _rotl(s[b] ^ s[c], 12)
    s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = _rotl(s[d] ^ s[a], 8)
    s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = _rotl(s[b] ^ s[c], 7)


def hchacha20(key: bytes, nonce16: bytes) -> bytes:
    s = [0x61707865, 0x3320646E, 0x79622D32, 0x6B206574]
    s += list(struct.unpack("<8I", key)) + list(struct.unpack("<4I", nonce16))
    for _ in range(10):
        _quarter(s, 0, 4, 8, 12); _quarter(s, 1, 5, 9, 13); _quarter(s, 2, 6, 10, 14); _quarter(s, 3, 7, 11, 15)
        _quarter(s, 0, 5, 10, 15); _quarter(s, 1, 6, 11, 12); _quarter(s, 2, 7, 8, 13); _quarter(s, 3, 4, 9, 14)
    return struct.pack("<8I", *(s[0:4] + s[12:16]))


def xchacha_encrypt(key: bytes, nonce24: bytes, aad: bytes, pt: bytes) -> bytes:
    subkey = hchacha20(key, nonce24[:16])
    return ChaCha20Poly1305(subkey).encrypt(b"\x00\x00\x00\x00" + nonce24[16:], pt, aad)


def xchacha_decrypt(key: bytes, nonce24: bytes, aad: bytes, ct_and_tag: bytes) -> bytes:
    subkey = hchacha20(key, nonce24[:16])
    return ChaCha20Poly1305(subkey).decrypt(b"\x00\x00\x00\x00" + nonce24[16:], ct_and_tag, aad)


# draft-irtf-cfrg-xchacha-03 A.2.1 (HChaCha20) and A.3.1 (XChaCha20-Poly1305)
assert hchacha20(bytes(range(32)), bytes.fromhex("000000090000004a0000000031415927")).hex() == \
    "82413b4227b27bfed30e42508a877d73a0f9e4d58a74a853c12ec41326d3ecdc", "HChaCha20 vector mismatch"
_DRAFT_PT = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
_DRAFT_CT = xchacha_encrypt(bytes(range(0x80, 0xA0)), bytes(range(0x40, 0x58)), bytes.fromhex("50515253c0c1c2c3c4c5c6c7"), _DRAFT_PT)
assert _DRAFT_CT.hex().startswith("bd6d179d3e83d43b9576579493c0e939572a1700252bfaccbed2902c21396cbb"), "XChaCha20 draft vector mismatch"
assert _DRAFT_CT.hex().endswith("c0875924c1c7987947deafd8780acf49"), "XChaCha20 draft tag mismatch"


# ---------------------------------------------------------------- vectors
def hkdf(ikm: bytes, salt: bytes, info: bytes, length: int = 32) -> bytes:
    return HKDF(algorithm=hashes.SHA512(), length=length, salt=salt, info=info).derive(ikm)


def argon2id(password: bytes, salt: bytes, m: int, t: int, p: int) -> bytes:
    return Argon2id(salt=salt, length=32, iterations=t, lanes=p, memory_cost=m).derive(password)


def rust_str(s: str) -> str:
    return '"' + "".join(c if (c.isascii() and c.isprintable() and c not in '"\\') else "\\u{%x}" % ord(c) for c in s) + '"'


def build() -> str:
    lines = [
        "// @generated by scripts/gen_crypto_kat.py from independent implementations. Do not edit by hand.",
        "// Spec: ai-docs/CRYPTO_SPEC.md",
        "#![allow(dead_code)]",
        "",
    ]
    # --- Argon2id
    salt = bytes(range(32))
    pw = "correct horse battery staple"
    lines.append(f'pub const ARGON2_SALT_HEX: &str = "{salt.hex()}";')
    lines.append("/// (password, m KiB, t, p, expected 32-byte output hex)")
    lines.append("pub const ARGON2_VECTORS: &[(&str, u32, u32, u32, &str)] = &[")
    for m, t, p in [(19456, 2, 1), (19456, 3, 2), (65536, 4, 4)]:
        lines.append(f'    ({rust_str(pw)}, {m}, {t}, {p}, "{argon2id(pw.encode(), salt, m, t, p).hex()}"),')
    lines.append("];")
    # --- NFKC
    samples = ["café", "café", "１２３abc", "ﬁnd", "Ångström", "x²+y²",
               "한글", "ΩΩ", "pässwörd €100", "½ cup"]
    lines.append("")
    lines.append("/// (input, expected NFKC UTF-8 hex)")
    lines.append("pub const NFKC_VECTORS: &[(&str, &str)] = &[")
    for s in samples:
        lines.append(f'    ({rust_str(s)}, "{unicodedata.normalize("NFKC", s).encode().hex()}"),')
    lines.append("];")
    # --- sub-keys
    root = bytes(range(32))
    uuid = "3f2b8c1e-5d4a-4e7b-9c1d-0a1b2c3d4e5f"
    lines.append("")
    lines.append("/// Root key is bytes 0..32. (label, context, expected hex)")
    lines.append("pub const SUBKEY_VECTORS: &[(&str, &str, &str)] = &[")
    for label, ctx in [("keyring", ""), ("vrk-commit", ""), ("item", uuid), ("version", uuid), ("attachment", uuid), ("meta", "s3-targets")]:
        info = b"passman/v1\x00" + label.encode() + b"\x00" + ctx.encode()
        lines.append(f'    ("{label}", "{ctx}", "{hkdf(root, b"passman/v1/hkdf", info).hex()}"),')
    lines.append("];")
    # --- hybrid combiner
    ss_m, ss_x = bytes([0x11] * 32), bytes([0x22] * 32)
    ct = bytes(i % 251 for i in range(1568))
    pk_e, pk_x = bytes([0x33] * 32), bytes([0x44] * 32)
    wrap = hkdf(ss_m + ss_x, b"passman/v1/hybrid-kem-salt", b"passman/v1/hybrid-kem\x00" + ct + pk_e + pk_x)
    lines.append("")
    lines.append("/// ss_M=[0x11;32], ss_X=[0x22;32], ct_M[i]=(i%251), pk_E=[0x33;32], pk_X=[0x44;32]")
    lines.append(f'pub const COMBINER_EXPECTED_HEX: &str = "{wrap.hex()}";')
    # --- XChaCha20-Poly1305
    lines.append("")
    lines.append("/// (key, nonce, aad, plaintext, ciphertext||tag), all hex. First entry is the IETF draft vector.")
    lines.append("pub const XCHACHA_VECTORS: &[(&str, &str, &str, &str, &str)] = &[")
    cases = [
        (bytes(range(0x80, 0xA0)), bytes(range(0x40, 0x58)), bytes.fromhex("50515253c0c1c2c3c4c5c6c7"), _DRAFT_PT),
        (bytes([0x42] * 32), bytes([0x07] * 24), b"", b""),
        (bytes(range(32)), bytes(range(24)), b"header-bytes", b"x"),
    ]
    for k, n, a, p in cases:
        lines.append(f'    ("{k.hex()}", "{n.hex()}", "{a.hex()}", "{p.hex()}", "{xchacha_encrypt(k, n, a, p).hex()}"),')
    lines.append("];")
    # --- envelope
    key, nonce = bytes(range(32)), bytes(range(24))
    header = json.dumps(
        {"v": 1, "kem": "ML-KEM-1024+X25519", "kdf": "Argon2id", "aead": "XChaCha20-Poly1305",
         "itemId": "kat-object-1", "version": 7, "timestamp": 1732360000000},
        separators=(",", ":"),
    ).encode()
    plaintext = b"envelope known answer"
    envelope = b"PMV1" + struct.pack(">I", len(header)) + header + nonce + xchacha_encrypt(key, nonce, header, plaintext)
    lines.append("")
    lines.append("/// Key = bytes 0..32, nonce = bytes 0..24, itemId `kat-object-1`, version 7, timestamp 1732360000000.")
    lines.append(f'pub const ENVELOPE_PLAINTEXT: &str = "{plaintext.decode()}";')
    lines.append(f'pub const ENVELOPE_HEX: &str = "{envelope.hex()}";')
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes); HChaCha20 and XChaCha20 draft vectors verified")
