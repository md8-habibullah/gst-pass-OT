#!/usr/bin/env bash
# Build the signed pacman repository (Arch, CachyOS, Manjaro, EndeavourOS ...) that scripts/install.sh registers.
# pacman's own tools (makepkg, repo-add) only exist on Arch, so this runs them inside an `archlinux` container: docker is the only
# requirement on the host. The package is made from the release tarball (the binary CI already built); nothing is compiled.
#
#   scripts/make-arch-repo.sh --out site-dist --site https://you.github.io/project --tarball hexis-0.1.0-linux-x86_64.tar.gz \
#       --gnupghome DIR --key FINGERPRINT            # the key from `scripts/make-repos.sh` / `github-setup.sh repo-key`
# (or REPO_SIGNING_KEY with the armored private key, as make-repos.sh takes it; REPO_SIGNING_PASSPHRASE is optional.)
#
# Output under --out:  arch/x86_64/{hexis.db, hexis.db.sig, hexis.files, hexis.files.sig,
#                                   hexis-<ver>-1-x86_64.pkg.tar.zst, ...pkg.tar.zst.sig}   (real files, no symlinks: Pages refuses links)
set -euo pipefail

OUT=""; SITE=""; TARBALL=""; GNUPGHOME_ARG=""; KEY_ARG=""
while [ $# -gt 0 ]; do
    case $1 in
        --out) OUT=$2; shift ;;
        --site) SITE=${2%/}; shift ;;
        --tarball) TARBALL=$2; shift ;;
        --gnupghome) GNUPGHOME_ARG=$2; shift ;;
        --key) KEY_ARG=$2; shift ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done
if [ -z "$OUT" ] || [ -z "$SITE" ] || [ ! -f "$TARBALL" ]; then echo "need --out, --site and --tarball FILE (see --help)" >&2; exit 2; fi
command -v docker >/dev/null || { echo "docker is needed (makepkg and repo-add run in an archlinux container)" >&2; exit 2; }
IMAGE=${ARCH_IMAGE:-archlinux:latest}

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
chmod 700 "$WORK"
# the signing key, as an armored file the container imports
if [ -n "$GNUPGHOME_ARG" ]; then
    FPR=${KEY_ARG:-$(GNUPGHOME=$GNUPGHOME_ARG gpg --batch --list-secret-keys --with-colons | awk -F: '/^fpr:/ {print $10; exit}')}
    EXPORT=(gpg --batch --armor)
    if [ -n "${REPO_SIGNING_PASSPHRASE:-}" ]; then EXPORT+=(--pinentry-mode loopback --passphrase "$REPO_SIGNING_PASSPHRASE"); fi
    GNUPGHOME=$GNUPGHOME_ARG "${EXPORT[@]}" --export-secret-keys "$FPR" >"$WORK/secret.asc"
else
    [ -n "${REPO_SIGNING_KEY:-}" ] || { echo "REPO_SIGNING_KEY is not set (and no --gnupghome)" >&2; exit 2; }
    printf '%s\n' "$REPO_SIGNING_KEY" >"$WORK/secret.asc"
    FPR=${KEY_ARG:-}
fi
chmod 600 "$WORK/secret.asc"
if [ -n "${REPO_SIGNING_PASSPHRASE:-}" ]; then printf '%s' "$REPO_SIGNING_PASSPHRASE" >"$WORK/pass"; else : >"$WORK/pass"; fi
chmod 600 "$WORK/pass"
cp "$TARBALL" "$WORK/"
TARNAME=$(basename "$TARBALL")
VERSION=${TARNAME#hexis-}; VERSION=${VERSION%-linux-x86_64.tar.gz}
[ "$VERSION" != "$TARNAME" ] || { echo "unexpected tarball name: $TARNAME (want hexis-<version>-linux-x86_64.tar.gz)" >&2; exit 2; }

cat >"$WORK/PKGBUILD" <<EOF
# Binary package of the release tarball; generated by scripts/make-arch-repo.sh
pkgname=hexis
pkgver=${VERSION//-/_}
pkgrel=1
pkgdesc='Post-quantum zero-knowledge password vault with multi-S3 sync (works offline)'
arch=('x86_64')
url='${SITE}/'
license=('MIT')
depends=('webkit2gtk-4.1' 'gtk3')
options=('!strip' '!debug' '!lto')
source=("${TARNAME}")
sha256sums=('SKIP')
package() {
  cd "hexis-${VERSION}"
  install -Dm755 hexis "\$pkgdir/usr/bin/hexis"
  install -Dm644 hexis.desktop "\$pkgdir/usr/share/applications/hexis.desktop"
  install -Dm644 hexis.png "\$pkgdir/usr/share/icons/hicolor/128x128/apps/hexis.png"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/hexis/LICENSE"
}
EOF

cat >"$WORK/build.sh" <<'EOF'
set -euo pipefail
pacman -Sy --noconfirm --needed fakeroot binutils >/dev/null 2>&1
useradd -m builder
mkdir -p /build /out && cp /work/PKGBUILD /work/*.tar.gz /build/ && chown -R builder /build
su builder -c 'cd /build && makepkg -f --nodeps --skippgpcheck --noconfirm' >/tmp/makepkg.log 2>&1 || { cat /tmp/makepkg.log; exit 1; }
export GNUPGHOME=/tmp/gnupg; mkdir -m 700 "$GNUPGHOME"
gpg --batch --quiet --import /work/secret.asc
FPR=${FPR:-$(gpg --batch --list-secret-keys --with-colons | awk -F: '/^fpr:/ {print $10; exit}')}
SIGN=(gpg --batch --yes --pinentry-mode loopback --local-user "$FPR")
if [ -s /work/pass ]; then SIGN+=(--passphrase-file /work/pass); fi
cd /build
PKG=$(ls hexis-*.pkg.tar.zst)
"${SIGN[@]}" --detach-sign --no-armor -o "$PKG.sig" "$PKG"
repo-add hexis.db.tar.zst "$PKG" >/dev/null
for f in hexis.db hexis.files; do
    cp --remove-destination "$f.tar.zst" "$f"          # pacman asks for hexis.db; a real file, not a symlink
    "${SIGN[@]}" --detach-sign --no-armor -o "$f.sig" "$f"
done
mkdir -p /out/arch/x86_64
cp -f "$PKG" "$PKG.sig" hexis.db hexis.db.sig hexis.files hexis.files.sig hexis.db.tar.zst hexis.files.tar.zst /out/arch/x86_64/
chown -R "$HOST_UID:$HOST_GID" /out/arch
echo "built $PKG"
EOF

mkdir -p "$OUT"; OUT=$(cd "$OUT" && pwd)
docker run --rm -e FPR="$FPR" -e HOST_UID="$(id -u)" -e HOST_GID="$(id -g)" \
    -v "$WORK:/work:ro" -v "$OUT:/out" "$IMAGE" bash /work/build.sh
find "$OUT/arch/x86_64" -type f -printf '%s  %f\n' | sort -k2
